import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawn, spawnSync } from 'node:child_process';
import { DatabaseSync } from 'node:sqlite';
import { Store } from '../platform/store.ts';
import { createServer } from '../platform/server.ts';
import { CollabClient } from '../sdk/client.ts';
const adminToken = 'admin-token-123456789012345678';
const agentToken = 'agent-token-123456789012345678';
const otherToken = 'other-token-123456789012345678';
const coordinatorToken = 'coordinator-token-123456789012345';
const ownerToken = 'owner-token-123456789012345678';
test('HTTP collaboration, isolation, idempotency, restart and knowledge lifecycle', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'collab-'));
    const path = join(dir, 'db.sqlite');
    let store = await Store.open(process.env.COLLAB_TEST_DATABASE ?? path);
    await store.bootstrap({ id: 'admin', workspace: 'acme', roles: ['admin', 'owner', 'reviewer'], token: adminToken, active: true });
    const server = createServer(store);
    await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
    const port = (server.address() as any).port;
    const url = `http://127.0.0.1:${port}`;
    const admin = new CollabClient(url, adminToken), agent = new CollabClient(url, agentToken), other = new CollabClient(url, otherToken), coordinator = new CollabClient(url, coordinatorToken), owner = new CollabClient(url, ownerToken);
    try {
        await admin.request('principals', { id: 'inventory', roles: ['agent'], token: agentToken }, 'reg1');
        await admin.request('principals', { id: 'other', roles: ['agent'], token: otherToken }, 'reg2');
        await admin.request('principals', { id: 'coordinator', roles: ['agent'], token: coordinatorToken }, 'reg3');
        await admin.request('principals', { id: 'owner2', roles: ['owner'], token: ownerToken }, 'reg4');
        const page = await fetch(url);
        assert.equal(page.status, 200);
        assert.match(await page.text(), /Anpio Collab/);
        const input = { title: 'shortage', material: 'M-100', quantity: 100, due: '2027-01-01T00:00:00Z', acceptance: 'verify sources' };
        const replayTask = await admin.request('tasks', { ...input, title: 'replay authorization' }, 'replay-task');
        await admin.request(`tasks/${replayTask.id}/coordinators`, { principal: 'coordinator' }, 'replay-delegate');
        await coordinator.request(`tasks/${replayTask.id}/assign`, { agent: 'coordinator', kind: 'self' }, 'replay-assign');
        await admin.request(`tasks/${replayTask.id}/remove-coordinator`, { principal: 'coordinator' }, 'replay-remove');
        assert.equal((await coordinator.task(replayTask.id)).id, replayTask.id);
        await assert.rejects(coordinator.request(`tasks/${replayTask.id}/assign`, { agent: 'coordinator', kind: 'self' }, 'replay-assign'), /403/);
        const task = await admin.request('tasks', input, 'create');
        assert.deepEqual(await admin.request('tasks', input, 'create'), task);
        await assert.rejects(admin.request('tasks', { ...input, quantity: 2 }, 'create'), /409/);
        await assert.rejects(coordinator.request(`tasks/${task.id}/assign`, { agent: 'inventory', kind: 'inventory' }, 'not-delegated'), /403/);
        await admin.request(`tasks/${task.id}/coordinators`, { principal: 'coordinator' }, 'delegate');
        await coordinator.request(`tasks/${task.id}/stage-summaries`, { text: 'Awaiting stock', pending: 'Inventory check' }, 'stage1');
        assert.equal((await coordinator.context(task.id)).stageSummary.stale, false);
        const sub = await coordinator.request(`tasks/${task.id}/assign`, { agent: 'inventory', kind: 'inventory' }, 'assign');
        assert.equal((await coordinator.context(task.id)).stageSummary.stale, true);
        assert.equal((await agent.context(task.id)).stageSummary, null);
        await assert.rejects(other.task(task.id), /403/);
        await assert.rejects(other.accept(sub.id, 'unauthorized'), /403/);
        assert.equal((await agent.inbox()).length, 1);
        const notices = await agent.notifications();
        assert.equal(notices.length, 1);
        await assert.rejects(other.acknowledge(notices[0].id, 'wrong-ack'), /404/);
        await agent.acknowledge(notices[0].id, 'ack');
        await agent.acknowledge(notices[0].id, 'ack');
        assert.equal((await agent.notifications()).length, 0);
        assert.equal((await agent.inbox()).length, 1);
        await agent.reject(sub.id, 'temporarily unavailable', 'reject');
        assert.equal((await agent.inbox()).length, 0);
        await admin.request(`subtasks/${sub.id}/return`, { note: 'please retry' }, 'return');
        await agent.accept(sub.id, 'accept');
        await agent.progress(sub.id, 'checking inventory', 'progress');
        assert.equal((await admin.task(task.id)).events.filter((e: any) => e.type === 'subtask_progress').length, 1);
        await agent.progress(sub.id, 'checking inventory', 'progress');
        assert.equal((await admin.task(task.id)).events.filter((e: any) => e.type === 'subtask_progress').length, 1);
        await assert.rejects(other.progress(sub.id, 'not mine', 'bad-progress'), /403/);
        const result = { quantity: 30, source: 'inventory fixture', observedAt: '2026-10-28T00:00:00Z' };
        await agent.submit(sub.id, result, 'submit');
        assert.equal((await agent.submit(sub.id, result, 'submit')).status, 'submitted');
        const journalPath = join(dir, 'worker.sqlite');
        const journal = new DatabaseSync(journalPath);
        journal.exec('CREATE TABLE pending (operation TEXT PRIMARY KEY, path TEXT NOT NULL, body TEXT NOT NULL); CREATE TABLE journal_meta(key TEXT PRIMARY KEY,value TEXT NOT NULL)');
        journal.prepare('INSERT INTO journal_meta VALUES(?,?)').run('binding',JSON.stringify({url,principal:'inventory',workspace:'acme'}));
        journal.prepare('INSERT INTO pending VALUES(?,?,?)').run('submit', `subtasks/${sub.id}/submit`, JSON.stringify({ result }));
        journal.close();
        await new Promise<void>((resolve, reject) => {
            const child = spawn(process.execPath, ['agents-ts/worker.ts'], { env: { ...process.env, COLLAB_URL: url, COLLAB_TOKEN: agentToken, COLLAB_KIND: 'inventory', COLLAB_DATA: 'examples/inventory.json', COLLAB_WORKER_DB: journalPath }, stdio: 'pipe' });
            let err = '';
            child.stderr.on('data', b => err += b);
            child.on('error', reject);
            child.on('exit', code => code === 0 ? resolve() : reject(new Error(err)));
        });
        const recovered = new DatabaseSync(journalPath);
        assert.equal((recovered.prepare('SELECT count(*) AS n FROM pending').get() as any).n, 0);
        recovered.close();
        assert.equal((await agent.task(task.id)).events.length, 0);
        await coordinator.request(`tasks/${task.id}/summary`, { text: 'shortage 70' }, 'summary');
        await assert.rejects(coordinator.request(`tasks/${task.id}/review`, { decision: 'accept', note: 'not authorized' }, 'review-denied'), /403/);
        await admin.request(`tasks/${task.id}/review`, { decision: 'return', note: 'clarify' }, 'review-return');
        await admin.request(`subtasks/${sub.id}/return`, { note: 'update' }, 'return2');
        await agent.accept(sub.id, 'accept2');
        await agent.submit(sub.id, { ...result, quantity: 35 }, 'submit2');
        await admin.request(`tasks/${task.id}/summary`, { text: 'shortage 65' }, 'summary2');
        await admin.request(`tasks/${task.id}/review`, { decision: 'accept', note: 'verified' }, 'review');
        assert.equal((await admin.task(task.id)).subtasks[0].status, 'verified');
        await assert.rejects(agent.progress(sub.id, 'too late', 'late-progress'), /409/);
        await admin.request(`tasks/${task.id}/remove-coordinator`, { principal: 'coordinator' }, 'remove-coordinator');
        await assert.rejects(coordinator.task(task.id), /403/);
        await assert.rejects(coordinator.request(`tasks/${task.id}/assign`, { agent: 'inventory', kind: 'inventory' }, 'assign'), /403/);
        const item = await admin.request(`tasks/${task.id}/knowledge`, { content: 'check stock', conditions: 'M-100' }, 'candidate');
        assert.equal((await agent.knowledge()).length, 0);
        assert.equal((await admin.request('knowledge/candidates')).length, 1);
        await assert.rejects(agent.request('knowledge/candidates'), /403/);
        await admin.request(`knowledge/${item.id}/publish`, { expiresAt: '2099-01-01T00:00:00Z', audience: ['inventory'] }, 'publish');
        assert.equal((await agent.knowledge()).length, 1);
        assert.equal((await other.knowledge()).length, 0);
        const ownerTask = await owner.request('tasks', { ...input, title: 'restricted reference' }, 'owner-task');
        await assert.rejects(owner.request(`tasks/${ownerTask.id}/references`, { knowledgeId: item.id }, 'denied-ref'), /404/);
        await admin.request(`knowledge/${item.id}/access`, { audience: ['inventory', 'owner2'] }, 'grant-owner');
        await owner.request(`tasks/${ownerTask.id}/references`, { knowledgeId: item.id }, 'owner-ref');
        assert.equal((await owner.task(ownerTask.id)).knowledgeRefs.length, 1);
        assert.equal((await owner.evidence(ownerTask.id, item.id, 1)).content, 'check stock');
        await assert.rejects(other.evidence(ownerTask.id, item.id, 1), /403/);
        assert.equal((await agent.knowledge('M-100')).length, 1);
        assert.equal((await agent.knowledge('not-found')).length, 0);
        const second = await admin.request('tasks', { ...input, title: 'second' }, 'create2');
        const own = await admin.request(`tasks/${second.id}/assign`, { agent: 'other', kind: 'custom' }, 'custom-assign');
        async function cli(args: string[], stdin = '') {
            return new Promise<any>((resolve, reject) => {
                const child = spawn(process.execPath, ['agents-ts/cli.ts', ...args], { env: { ...process.env, COLLAB_URL: url, COLLAB_TOKEN: otherToken } });
                let out = '', err = '';
                child.stdout.on('data', b => out += b);
                child.stderr.on('data', b => err += b);
                child.on('error', reject);
                child.on('exit', code => code === 0 ? resolve(JSON.parse(out)) : reject(new Error(err)));
                child.stdin.end(stdin);
            });
        }
        assert.equal((await cli(['inbox']))[0].id, own.id);
        await admin.request(`subtasks/${own.id}/timeout`, { note: 'waiting for status reconciliation' }, 'timeout');
        assert.equal((await cli(['inbox'])).length, 0);
        await admin.request(`subtasks/${own.id}/return`, { note: 'confirmed safe to retry' }, 'reopen');
        await cli(['accept', own.id, 'cli-accept']);
        const custom = { summary: 'External agent result', source: 'manual fixture', observedAt: '2026-10-28T00:00:00Z' };
        assert.equal((await cli(['submit', own.id, 'cli-submit'], JSON.stringify(custom))).status, 'submitted');
        assert.equal((await admin.task(second.id)).subtasks[0].result.summary, custom.summary);
        await admin.request(`tasks/${second.id}/references`, { knowledgeId: item.id }, 'ref');
        await admin.request(`knowledge/${item.id}/access`, { audience: ['other'] }, 'access-change');
        assert.equal((await agent.knowledge()).length, 0);
        assert.equal((await other.knowledge()).length, 1);
        assert.equal((await owner.task(ownerTask.id)).knowledgeRefs.length, 0);
        assert.equal((await owner.task(ownerTask.id)).events.some((e: any) => e.type === 'knowledge_referenced'), false);
        await assert.rejects(owner.request(`tasks/${ownerTask.id}/references`, { knowledgeId: item.id }, 'owner-ref'), /404/);
        await assert.rejects(owner.evidence(ownerTask.id, item.id, 1), /404/);
        await admin.request(`knowledge/${item.id}/revoke`, { reason: 'outdated' }, 'revoke');
        assert.equal((await admin.evidence(second.id, item.id, 1)).currentState, 'revoked');
        assert.equal((await agent.knowledge()).length, 0);
        assert.equal((await admin.task(second.id)).knowledgeRefs[0].version, 1);
        await assert.rejects(admin.request(`tasks/${second.id}/references`, { knowledgeId: item.id }, 'ref2'), /404/);
        const revision = await admin.request(`knowledge/${item.id}/revise`, { content: 'updated stock advice', conditions: 'M-100', reason: 'new evidence' }, 'revise');
        assert.equal(revision.version, 2);
        assert.equal((await agent.knowledge()).length, 0);
        await admin.request(`knowledge/${item.id}/publish`, { expiresAt: '2099-01-01T00:00:00Z', audience: 'workspace' }, 'publish2');
        assert.equal((await admin.request(`knowledge/${item.id}/versions`)).length, 2);
        assert.equal((await admin.task(second.id)).knowledgeRefs[0].version, 1);
        assert.equal((await admin.request('tasks/page?limit=1')).items.length, 1);
        assert.equal((await admin.request('tasks/page?limit=1')).nextOffset, 1);
        await assert.rejects(admin.request('tasks/page?limit=0'), /400/);
        assert.equal((await admin.request(`tasks/${second.id}/context`)).task.id, second.id);
        await assert.rejects(other.request(`tasks/${task.id}/context`), /403/);
        const audit = await admin.request('audit');
        assert.ok(audit.some((entry: any) => entry.action.includes('/review') && entry.outcome === 'denied:403'));
        assert.ok(audit.some((entry: any) => entry.action.includes('/revoke') && entry.outcome === 'success'));
        await assert.rejects(other.request('audit'), /403/);
        await admin.request('principals/inventory/deactivate', {}, 'deactivate');
        await assert.rejects(agent.inbox(), /401/);
    }
    finally {
        await new Promise<void>((resolve, reject) => server.close(e => e ? reject(e) : resolve()));
        await store.close();
    }
    if(process.env.COLLAB_TEST_DATABASE) { rmSync(dir,{recursive:true,force:true}); return; }
    const backup = join(dir, 'backup.sqlite');
    const backupRun = spawnSync(process.execPath, ['platform/backup.ts', path, backup], { encoding: 'utf8' });
    assert.equal(backupRun.status, 0, backupRun.stderr);
    store = await Store.open(backup);
    assert.equal((await store.authenticate(adminToken)).id, 'admin');
    assert.equal((await store.all('SELECT * FROM tasks')).length, 4);
    await store.close();
    rmSync(dir, { recursive: true, force: true });
});
